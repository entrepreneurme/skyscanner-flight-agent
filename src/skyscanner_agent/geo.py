# Sub-regions users often pick in Skyscanner-style exploration
REGION_COUNTRY_IDS: dict[str, set[str]] = {
    "Southeast Asia": {"BN", "KH", "ID", "LA", "MY", "MM", "PH", "SG", "TH", "TL", "VN"},
    "Western Europe": {"AT", "BE", "FR", "DE", "IE", "LU", "NL", "CH", "GB", "PT", "ES"},
    "Eastern Europe": {"BG", "CZ", "HU", "PL", "RO", "SK", "UA", "EE", "LV", "LT"},
}

REGION_ALIASES: dict[str, str] = {
    "southeast asia": "Southeast Asia",
    "western europe": "Western Europe",
    "eastern europe": "Eastern Europe",
}


def normalize_continent(name: str) -> str:
    key = name.strip().lower()
    if key in REGION_ALIASES:
        return REGION_ALIASES[key]
    if key in CONTINENT_ALIASES:
        return CONTINENT_ALIASES[key]
    for canonical in set(CONTINENT_ALIASES.values()) | set(REGION_COUNTRY_IDS.keys()):
        if canonical.lower() == key:
            return canonical
    raise ValueError(f"Unknown continent or region: {name!r}")


def country_matches_location_filters(
    country_id: str | None,
    *,
    continents: set[str],
    regions: set[str],
) -> bool:
    if not continents and not regions:
        return True
    if not country_id:
        return False
    code = country_id.upper()
    if regions:
        for region in regions:
            if code in REGION_COUNTRY_IDS.get(region, set()):
                return True
    if continents:
        continent = COUNTRY_TO_CONTINENT.get(code)
        return continent in continents if continent else False
    return False


def normalize_country_name(name: str) -> str:
    return name.strip().lower()
